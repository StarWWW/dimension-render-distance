# the same pattern the game uses; anything else with a % in it is shown as raw text
FORMAT = re.compile(r"%(?:(\d+)\$)?([A-Za-z%]|$)")


def arguments(text):
    """Number of %s arguments, or -1 if the game cannot format the text."""
    count, current = 0, 0
    for m in FORMAT.finditer(text):
        if "%" in text[current:m.start()]:
            return -1
        if m.group(0) == "%%":
            pass
        elif m.group(2) == "s":
            count += 1
        else:
            return -1
        current = m.end()
    return -1 if "%" in text[current:] else count


def full_key(key):
    return key if key.startswith("key.") else "dimrender." + key


def main():
    errors = []
    english = T["en_us"]
    for code, table in T.items():
        if list(table) != list(english):
            errors.append(f"{code}: keys differ from en_us")
            continue
        for key, text in table.items():
            if arguments(text) < 0:
                errors.append(f"{code}: {key} has a % that is not %s or %%")
            elif arguments(text) != arguments(english[key]):
                errors.append(f"{code}: {key} placeholder count differs")
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    for old in OUT.glob("*.json"):
        old.unlink()
    OUT.mkdir(parents=True, exist_ok=True)
    for code, table in T.items():
        data = {full_key(k): v for k, v in table.items()}
        # newline="\n": the same files on every OS
        (OUT / f"{code}.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8",
                                         newline="\n")
    print(f"wrote {len(T)} languages, {len(english)} keys each")


if __name__ == "__main__":
    main()
